-- ---------- Profil admin / pemetaan akun Supabase Auth ----------
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique,
  nama text not null default '',
  role text not null default 'Aparat',
  is_active boolean not null default false,
  created_at timestamptz not null default now()
);

-- Pengguna Auth baru dibuat NONAKTIF. Aktivasi/promosi pertama dilakukan
-- manual lewat SQL Editor, bukan dari browser/public key.
create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_username text;
begin
  v_username := lower(split_part(coalesce(new.email, new.phone, new.id::text), '@', 1));
  v_username := regexp_replace(v_username, '[^a-z0-9._-]+', '_', 'g');

  insert into public.profiles (id, username, nama, role, is_active)
  values (
    new.id,
    v_username,
    coalesce(nullif(new.raw_user_meta_data ->> 'nama', ''), v_username),
    'Aparat',
    false
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile
after insert on auth.users
for each row execute procedure public.handle_new_auth_user();

create or replace function public.is_active_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = (select auth.uid()) and p.is_active = true
  );
$$;

create or replace function public.is_super_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = (select auth.uid())
      and p.is_active = true
      and lower(p.role) = 'super admin'
  );
$$;

revoke all on function public.is_active_admin() from public;
revoke all on function public.is_super_admin() from public;
grant execute on function public.is_active_admin() to authenticated;
grant execute on function public.is_super_admin() to authenticated;

