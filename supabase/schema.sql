-- Hanya mengeluarkan angka agregat ke halaman publik; tidak pernah mengembalikan NIK/KK.
create or replace function public.public_population_stats()
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_build_object(
    'total_penduduk', count(*)::integer,
    'total_laki_laki', count(*) filter (where p.jenis_kelamin = 'L')::integer,
    'total_perempuan', count(*) filter (where p.jenis_kelamin = 'P')::integer,
    'total_kartu_keluarga', count(distinct nullif(btrim(p.no_kk), ''))::integer
  )
  from public.penduduk p;
$$;
revoke all on function public.public_population_stats() from public;
grant execute on function public.public_population_stats() to anon, authenticated;

