-- ---------- Supabase Storage ----------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'desa-public',
  'desa-public',
  true,
  10485760,
  array['image/jpeg','image/png','image/webp','application/pdf']
)
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "public read desa public files" on storage.objects;
create policy "public read desa public files" on storage.objects
for select to anon, authenticated
using (bucket_id = 'desa-public');

drop policy if exists "active admin upload desa files" on storage.objects;
create policy "active admin upload desa files" on storage.objects
for insert to authenticated
with check (bucket_id = 'desa-public' and public.is_active_admin());

drop policy if exists "active admin update desa files" on storage.objects;
create policy "active admin update desa files" on storage.objects
for update to authenticated
using (bucket_id = 'desa-public' and public.is_active_admin())
with check (bucket_id = 'desa-public' and public.is_active_admin());

drop policy if exists "active admin delete desa files" on storage.objects;
create policy "active admin delete desa files" on storage.objects
for delete to authenticated
using (bucket_id = 'desa-public' and public.is_active_admin());
