-- Public website hanya dapat membaca konten non-sensitif.
do $$
declare t text;
begin
  foreach t in array array['berita','pengumuman','galeri','dokumen','profil_desa','info_desa','riwayat','struktur'] loop
    execute format('drop policy if exists "public read %1$s" on public.%1$I', t);
    execute format('create policy "public read %1$s" on public.%1$I for select to anon, authenticated using (true)', t);
    execute format('drop policy if exists "admin manage %1$s" on public.%1$I', t);
    execute format('create policy "admin manage %1$s" on public.%1$I for all to authenticated using (public.is_active_admin()) with check (public.is_active_admin())', t);
  end loop;
end $$;

-- Profil admin: setiap user bisa membaca profilnya sendiri; admin aktif dapat melihat daftar aparat.
drop policy if exists "profiles read self or admin" on public.profiles;
create policy "profiles read self or admin" on public.profiles
for select to authenticated
using (id = (select auth.uid()) or public.is_active_admin());
drop policy if exists "super admin update profiles" on public.profiles;
create policy "super admin update profiles" on public.profiles
for update to authenticated
using (public.is_super_admin())
with check (public.is_super_admin());

-- Saran: pengunjung hanya boleh mengirim saran berstatus Baru; admin aktif bisa mengelola.
drop policy if exists "public submit saran" on public.saran;
create policy "public submit saran" on public.saran
for insert to anon, authenticated
with check (status = 'Baru');
drop policy if exists "admin manage saran" on public.saran;
create policy "admin manage saran" on public.saran
for all to authenticated
using (public.is_active_admin())
with check (public.is_active_admin());

-- Dusun dan penduduk sama sekali tidak bisa dibaca oleh role anon.
drop policy if exists "admin manage dusun" on public.dusun;
create policy "admin manage dusun" on public.dusun
for all to authenticated
using (public.is_active_admin())
with check (public.is_active_admin());
drop policy if exists "admin manage penduduk" on public.penduduk;
create policy "admin manage penduduk" on public.penduduk
for all to authenticated
